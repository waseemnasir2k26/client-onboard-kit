"""Turn a config + the templates into a pack of documents on disk."""

from __future__ import annotations

import datetime as _dt
import re
from dataclasses import dataclass
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateError, TemplateNotFound

from . import DISCLAIMER, __version__
from . import html as html_mod
from .config import Formatter, TrackedMapping, load_config
from .errors import (
    ConfigError,
    MissingFieldError,
    TemplateNotFoundError,
    UnrenderedPlaceholderError,
)

# Any of these surviving into output means a template did not render. Never ship it.
_PLACEHOLDER = re.compile(r"\{\{|\}\}|\{%|%\}|\{#|#\}")


@dataclass(frozen=True)
class Document:
    slug: str
    template: str
    title: str
    purpose: str
    legal: bool = False
    condition: str | None = None  # dotted config path that must be truthy


DOCUMENTS: tuple[Document, ...] = (
    Document(
        "service-agreement",
        "service-agreement.md",
        "Service Agreement",
        "Fixes scope, fees, revisions and IP, so a late extra request has a price attached.",
        legal=True,
    ),
    Document(
        "nda",
        "nda.md",
        "Non-Disclosure Agreement",
        "Lets both sides share real numbers and credentials before the contract is signed.",
        legal=True,
        condition="legal.nda.include_in_pack",
    ),
    Document(
        "intake-questionnaire",
        "intake-questionnaire.md",
        "Intake and Scoping Questionnaire",
        "Surfaces the unknowns that otherwise become change requests in week three.",
    ),
    Document(
        "kickoff",
        "kickoff.md",
        "Kickoff Document",
        "Names the approver, the channels, the response times and what the client owes you.",
    ),
    Document(
        "welcome-email",
        "welcome-email.md",
        "Welcome Email",
        "Sets the tone and the first three actions while the client is still enthusiastic.",
    ),
)

DOCUMENT_BY_SLUG = {d.slug: d for d in DOCUMENTS}


def bundled_templates_dir() -> Path:
    """Where templates live: inside the installed package, or `templates/` in the repo."""
    installed = Path(__file__).resolve().parent / "templates"
    if installed.is_dir():
        return installed
    source = Path(__file__).resolve().parent.parent / "templates"
    if source.is_dir():
        return source
    raise TemplateNotFoundError(
        "Could not locate the templates directory. Reinstall the package, or pass --templates."
    )


def _deep_get(cfg: TrackedMapping, path: str, default=None):
    node = cfg
    for part in path.split("."):
        if isinstance(node, TrackedMapping) and part in node:
            node = node[part]
        else:
            return default
    return node


def build_environment(templates_dir: Path, cfg: TrackedMapping) -> Environment:
    fmt_block = _deep_get(cfg, "format")
    formatter = Formatter(fmt_block.as_dict() if isinstance(fmt_block, TrackedMapping) else None)

    env = Environment(
        loader=FileSystemLoader(str(templates_dir), encoding="utf-8"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        autoescape=False,  # these are Markdown documents, not web pages
    )
    env.filters["money"] = formatter.money
    env.filters["date"] = formatter.date
    env.filters["pct"] = Formatter.pct
    # Upper-case the first character only, so config values can be written to read
    # naturally mid-sentence ("a shared Slack channel") and still start a table cell.
    env.filters["sentence"] = lambda text: (str(text)[:1].upper() + str(text)[1:]) if text else text
    # Multi-line YAML blocks (addresses) need Markdown hard line breaks.
    env.filters["block"] = lambda text: "  \n".join(
        line.strip() for line in str(text).strip().splitlines()
    )
    env.globals["opt"] = lambda path, default="": _deep_get(cfg, path, default)
    env.globals["has"] = lambda path: _deep_get(cfg, path, None) not in (None, "", [], {})
    env.globals["today"] = _dt.date.today()
    env.globals["kit_version"] = __version__
    return env


def _header_comment(doc: Document) -> str:
    stamp = _dt.date.today().isoformat()
    return (
        "<!--\n"
        f"  {doc.title.upper()} - DRAFT - NOT LEGAL ADVICE\n"
        f"  Generated by client-onboard-kit v{__version__} on {stamp}.\n"
        "\n"
        f"  {DISCLAIMER}\n"
        "\n"
        "  This comment does not appear in the printed or PDF output. Delete it if you\n"
        "  would rather it did not travel with the file at all.\n"
        "-->\n\n"
    )


def render_document(env: Environment, doc: Document, cfg: TrackedMapping) -> str:
    """Render one template to Markdown. Raises MissingFieldError naming the template."""
    try:
        template = env.get_template(doc.template)
    except TemplateNotFound:
        raise TemplateNotFoundError(
            f"Template '{doc.template}' not found in the templates directory."
        ) from None
    try:
        body = template.render(**{k: cfg[k] for k in cfg})
    except MissingFieldError as exc:
        raise MissingFieldError(exc.path, template=doc.template, hint=exc.hint) from None
    except TemplateError as exc:
        raise ConfigError(f"Template '{doc.template}' failed to render: {exc}") from None

    markdown = _header_comment(doc) + body.strip() + "\n"
    assert_fully_rendered(markdown, doc.template)
    return markdown


def assert_fully_rendered(text: str, template_name: str) -> None:
    """Hard gate: template syntax must never survive into a client-facing document."""
    if not _PLACEHOLDER.search(text):
        return
    snippets = []
    for match in _PLACEHOLDER.finditer(text):
        start = max(0, match.start() - 30)
        snippets.append(text[start : match.end() + 30].replace("\n", " ").strip())
    raise UnrenderedPlaceholderError(template_name, snippets)


def selected_documents(cfg: TrackedMapping, only: list[str] | None = None) -> list[Document]:
    if only:
        unknown = [s for s in only if s not in DOCUMENT_BY_SLUG]
        if unknown:
            raise ConfigError(
                "Unknown document(s): "
                + ", ".join(unknown)
                + ". Known: "
                + ", ".join(DOCUMENT_BY_SLUG)
            )
        chosen = [DOCUMENT_BY_SLUG[s] for s in only]
    else:
        chosen = list(DOCUMENTS)
    return [d for d in chosen if d.condition is None or bool(_deep_get(cfg, d.condition, False))]


def build_pack(
    config_path: str | Path,
    out_dir: str | Path,
    *,
    templates_dir: str | Path | None = None,
    only: list[str] | None = None,
    formats: tuple[str, ...] = ("md", "html"),
) -> list[Path]:
    cfg = load_config(config_path)
    tdir = Path(templates_dir) if templates_dir else bundled_templates_dir()
    if not tdir.is_dir():
        raise TemplateNotFoundError(f"Templates directory not found: {tdir}")

    env = build_environment(tdir, cfg)
    docs = selected_documents(cfg, only)
    if not docs:
        raise ConfigError(
            "Nothing to build: every document was excluded by --only or by a config toggle."
        )

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    entries: list[tuple[str, str, str]] = []

    client_label = str(
        _deep_get(cfg, "client.short_name", None) or _deep_get(cfg, "client.legal_name", "Client")
    )

    for doc in docs:
        markdown = render_document(env, doc, cfg)
        if "md" in formats:
            path = out / f"{doc.slug}.md"
            path.write_text(markdown, encoding="utf-8")
            written.append(path)
        if "html" in formats:
            page = html_mod.document(
                f"{doc.title} - {client_label}",
                markdown,
                legal=doc.legal,
                label=f"{doc.title} / {client_label}",
            )
            path = out / f"{doc.slug}.html"
            path.write_text(page, encoding="utf-8")
            written.append(path)
            entries.append((f"{doc.slug}.html", doc.title, doc.purpose))

    if "html" in formats:
        index_path = out / "index.html"
        index_path.write_text(
            html_mod.index(f"Onboarding pack - {client_label}", entries), encoding="utf-8"
        )
        written.append(index_path)

    return written
